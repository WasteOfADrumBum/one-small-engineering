// Unified engineering dashboard (Phase 5, docs/engineering.md). Pure and deterministic; every
// string is redacted on the way out. It extends the Phase 3 dashboard (reports/dashboard.md) and
// the Phase 4 verification dashboard (reports/verification/dashboard.md), which stay as the
// detailed views and are linked from here, instead of building a parallel reporting system.

import { redactJson } from '../release/render.mjs'
import { redactSensitive } from '../validate-registry.mjs'
import { ACTION_CLASSES, PRIORITIES } from './queue.mjs'
import { RELEASE_STATES, RELEASE_STATE_TEXT } from './release.mjs'

const cell = s => String(s ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|')
const short = sha => (sha ? sha.slice(0, 7) : 'none')
const day = t => (t ? t.slice(0, 10) : 'unknown')
const pct = (a, b) => (b ? `${Math.floor((a * 1000) / b) / 10}%` : 'n/a')
const proj = (r, id) => (id === 'portfolio' ? 'portfolio' : `[${id}](../projects/${id}.md)`)

function header(meta) {
  const run = meta.run
  return [
    `Generated by \`${meta.command}\` as of ${meta.asOf}${run ? ` from the ${run.mode} run of ${run.at} (${run.executor}${run.runUrl ? `, ${run.runUrl}` : ''})` : ''}. Do not edit by hand; regenerate.`,
    '',
    '> Observation, not authorization. Collector results are not verification, a release state is not approval, and nothing here merges, publishes or deploys. Only Joshua Small approves releases.',
    ''
  ]
}

function queueRow(i) {
  return `| ${i.rank} | ${cell(i.project === 'portfolio' ? `portfolio (${i.projects.join(', ')})` : i.project)} | ${i.priority}. ${cell(i.priorityText)} | ${i.severity} | ${cell(i.title)} | ${cell(i.nextAction)}${i.relatedPRs.length ? ` (${i.relatedPRs.map(p => `${p.url} ${p.status}${p.reviewed === false ? ', unreviewed' : ''}`).join('; ')})` : ''} | ${i.isNew ? 'new' : day(i.firstSeen)} |`
}

export function renderDashboard(r, meta) {
  const o = r.overview
  const L = ['# One Small Engineering: what needs attention', '', ...header(meta)]
  L.push('## Attention now', '')
  const now = r.queue.filter(i => i.actionClass !== 'informational').slice(0, 10)
  if (now.length) {
    L.push('| # | Project | Priority | Severity | Issue | Next action | Seen since |', '| --- | --- | --- | --- | --- | --- | --- |')
    for (const i of now) L.push(queueRow(i))
    L.push('', `Full ranked queue (${r.queue.length} issues): [queue.md](queue.md).`)
  } else L.push('Nothing needs attention.')
  L.push('', '## Portfolio', '')
  L.push('| Measure | Value |', '| --- | --- |')
  L.push(`| Active projects | ${o.activeProjects}${o.inaccessible.length ? ` (${o.inaccessible.length} not readable: ${o.inaccessible.join(', ')})` : ''} |`)
  L.push(`| Ready for release (approved or released) | ${o.readyForRelease} |`)
  L.push(`| Candidate ready or awaiting approval | ${o.candidateReady} |`)
  L.push(`| Blocked | ${o.blocked} |`)
  L.push(`| Failing CI | ${o.failingCi} (no current CI evidence for ${o.ciUnknown}) |`)
  L.push(`| Security findings | ${['critical', 'high', 'medium', 'low'].map(s => `${o.security[s]} ${s}`).join(', ')} |`)
  L.push(`| Verification coverage | ${o.verificationCoverage.verified} of ${o.verificationCoverage.applicable} applicable gates independently verified (${pct(o.verificationCoverage.verified, o.verificationCoverage.applicable)}) |`)
  L.push(`| Open remediation PRs | ${o.openRemediationPRs} (${o.unreviewedRemediationPRs} known unreviewed) |`)
  L.push(`| Stale evidence records | ${o.staleEvidence} |`)
  L.push(`| Cross-project dependency risks | ${o.dependencyRisks} ([dependencies.md](dependencies.md)) |`)
  L.push(`| Release states | ${RELEASE_STATES.filter(s => o.releaseStates[s]).map(s => `${o.releaseStates[s]} ${RELEASE_STATE_TEXT[s]}`).join(', ')} ([releases.md](releases.md)) |`)
  L.push(`| Queue by action | ${Object.entries(o.queue).map(([k, n]) => `${n} ${ACTION_CLASSES[k].toLowerCase()}`).join(', ')} |`)
  L.push('', '## Projects', '')
  L.push('| Project | Revision | Seen since | Access | CI | Verified | Release state | Blockers | Security (c/h/m/l) | Open PRs | Registry sync | Next action |')
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const p of r.projects) {
    L.push(`| [${cell(p.name)}](${p.repository}) | ${short(p.revision)} | ${day(p.revisionSeenSince)} | ${cell(p.access === 'readable' ? 'readable' : p.access)} | ${cell(p.ci)} | ${p.readiness.verifiedGates}/${p.readiness.applicableGates} (${p.readiness.percentage}%) | ${p.release.text}${p.previousReleaseState && p.previousReleaseState !== p.release.state ? ` (was ${RELEASE_STATE_TEXT[p.previousReleaseState]})` : ''} | ${p.blockers.length ? cell(p.blockers.map(b => b.id).join(', ')) : 'none'} | ${['critical', 'high', 'medium', 'low'].map(s => p.security[s]).join('/')} | ${p.openPullRequests} | ${cell(p.sync.status)} | ${cell(p.nextAction)} |`)
  }
  L.push('', '## Detail', '')
  L.push('- Verification evidence and gate states: [verification dashboard](../verification/dashboard.md)')
  L.push('- Registry readiness and release preparation: [release dashboard](../dashboard.md)')
  L.push('- Machine-readable: [dashboard.json](dashboard.json)')
  if (r.overlayErrors.length) L.push('', '## Verification records not applied', '', ...r.overlayErrors.map(e => `- ${cell(e)}`))
  L.push('')
  return redactSensitive(L.join('\n'))
}

export function renderQueue(r, meta) {
  const L = ['# Remediation queue', '', ...header(meta)]
  L.push(`${r.queue.length} issues, ranked by priority class, then severity, then project order. One id per underlying problem (no commit in the id), so the same issue keeps its id across revisions.`, '')
  L.push('Priority classes: ' + Object.entries(PRIORITIES).map(([k, t]) => `${k} ${t}`).join('; ') + '.', '')
  for (const [cls, text] of Object.entries(ACTION_CLASSES)) {
    const list = r.queue.filter(i => i.actionClass === cls)
    L.push(`## ${text} (${list.length})`, '')
    if (!list.length) { L.push('None.', ''); continue }
    L.push('| # | Project | Priority | Severity | Issue | Next action | Seen since |', '| --- | --- | --- | --- | --- | --- | --- |')
    for (const i of list) L.push(queueRow(i))
    L.push('')
  }
  L.push('## Issue detail', '')
  for (const i of r.queue) {
    L.push(`### ${i.rank}. ${cell(i.title)}`, '')
    L.push(`- Id: \`${i.id}\`; project: ${i.projects.join(', ')}${i.repository ? ` (${i.repository})` : ''}; revision: ${i.revision || 'n/a'}`)
    L.push(`- Priority: ${i.priority}. ${i.priorityText}; severity ${i.severity}; action: ${i.actionText}; confidence ${i.confidence}; complexity ${i.complexity}`)
    L.push(`- Root cause: ${cell(i.rootCause || 'not established')}`)
    L.push(`- Impact: ${cell(i.impact || 'not stated')}`)
    L.push(`- Proposed correction: ${cell(i.proposedCorrection || 'none')}`)
    L.push(`- Validation: ${cell(i.validation.join('; ') || 'none')}`)
    L.push(`- Evidence: ${i.evidence.length ? i.evidence.map(e => `\`${e}\``).join(', ') : 'none'}${i.relatedPRs.length ? `; PRs: ${i.relatedPRs.map(p => `${p.url} (${p.status})`).join(', ')}` : ''}${i.crossProject.length ? `; same package in: ${i.crossProject.join(', ')}` : ''}`)
    L.push('')
  }
  return redactSensitive(L.join('\n'))
}

export function renderDependencies(r, meta) {
  const d = r.dependencies
  const L = ['# Cross-project dependency impact', '', ...header(meta)]
  L.push('Confirmed relationships come from registry declarations with evidence, package manifests and workflow files at the evaluated commit. Nothing is inferred from names.', '')
  L.push('## Relationships', '')
  if (d.edges.length) {
    L.push('| From | To | Kind | Status | Required for release | Basis |', '| --- | --- | --- | --- | --- | --- |')
    for (const e of d.edges) L.push(`| ${e.from} | ${e.to} | ${e.kind} | ${e.confirmed ? 'confirmed' : 'suspected'} | ${e.requiredForRelease ? 'yes' : 'no'} | ${cell(e.basis)} |`)
  } else L.push('None.')
  L.push('', `Release order (dependencies first): ${d.releaseOrder.join(', ')}.`, '')
  L.push('## Follow-up verification needed', '')
  L.push(...(d.followUps.length ? d.followUps.map(f => `- ${cell(f.action)}`) : ['None: no project a confirmed dependent relies on changed since its dependents were last checked.']))
  L.push('', '## Risks', '')
  L.push(...(d.risks.length ? d.risks.map(x => `- ${x.severity}: ${cell(x.message)}`) : ['None.']))
  L.push('', `## Shared third-party packages (${d.sharedPackages.length} notable of ${d.sharedPackageCount} shared)`, '')
  if (d.sharedPackages.length) {
    L.push('| Package | Projects (locked version) | Major versions | Advisories |', '| --- | --- | --- | --- |')
    for (const s of d.sharedPackages) L.push(`| ${s.name} | ${cell(Object.entries(s.projects).map(([id, x]) => `${id} ${x.locked || x.spec}${x.dev ? ' (dev)' : ''}`).join(', '))} | ${s.majors.join(', ')} | ${cell(s.advisories.map(a => `${a.project} ${a.severity}`).join(', ') || 'none')} |`)
  } else L.push('None.')
  L.push('', '## Runtime floors (package.json engines.node)', '')
  L.push(...Object.entries(d.runtimeFloors).map(([id, f]) => `- ${id}: ${f || 'not declared'}`))
  if (d.manifestsMissing.length) L.push('', `Manifests not read (no checkout): ${d.manifestsMissing.join(', ')}. Their relationships are unknown, not absent.`)
  L.push('')
  return redactSensitive(L.join('\n'))
}

export function renderReleases(r, meta) {
  const L = ['# Release orchestration', '', ...header(meta)]
  L.push('States: ' + RELEASE_STATES.map(s => RELEASE_STATE_TEXT[s]).join(' -> ') + '. Moving past Candidate Ready needs the owner: putting the release up for review, then an approval recorded in the registry with evidence for the candidate commit. Merging, tagging, publishing and deploying stay owner actions.', '')
  L.push('| Project | State | Candidate | Verified gates | Why |', '| --- | --- | --- | --- | --- |')
  for (const p of r.projects) L.push(`| ${p.name} | ${p.release.text} | ${p.release.candidate ? `PR #${p.release.candidate.pullRequest} at ${short(p.release.candidate.sha)}` : 'none'} | ${p.releasePlan.verifiedGates}/${p.releasePlan.applicableGates} | ${cell(p.release.reasons.join('; ') || 'n/a')} |`)
  for (const p of r.projects) {
    const x = p.releasePlan
    L.push('', `## ${p.name}`, '')
    L.push(`- State: ${p.release.text}; candidate revision ${x.candidateRevision || 'none'} (${cell(x.candidateSource)})`)
    L.push(`- Version: ${cell(x.versionRecommendation)}`)
    L.push(`- Missing independent verification: ${x.missingEvidence.length ? x.missingEvidence.join(', ') : 'none'}`)
    L.push(`- Active blockers: ${x.activeBlockers.length ? x.activeBlockers.join(', ') : 'none'}`)
    L.push(`- Dependency readiness: ${x.dependencyReadiness.length ? cell(x.dependencyReadiness.join('; ')) : 'no declared or detected dependencies'}`)
    L.push(`- Manual testing required: ${x.manualTesting.length ? x.manualTesting.join(', ') : 'none'}`)
    L.push(`- Approvals required: ${x.approvalsRequired.join('; ')}`)
    L.push(`- Preparation: ${x.preparationStatus}`)
    L.push(`- Rollback: ${cell(x.rollback)}`)
  }
  L.push('')
  return redactSensitive(L.join('\n'))
}

export const toJson = v => JSON.stringify(redactJson(v), null, 2) + '\n'

export function renderAll(r, meta) {
  return {
    'dashboard.md': renderDashboard(r, meta),
    'queue.md': renderQueue(r, meta),
    'dependencies.md': renderDependencies(r, meta),
    'releases.md': renderReleases(r, meta),
    'dashboard.json': toJson({ kind: 'one-small-engineering/engineering-dashboard', schema: 1, command: meta.command, ...r })
  }
}
