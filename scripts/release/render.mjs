// Markdown and JSON renderers for release-readiness reports. Pure and deterministic: the output
// depends only on the assessment (and, for release preparation, the optional changelog text).
// Every string that leaves the process passes through redactSensitive.
//
// Each report separates three kinds of content, with the same labels everywhere:
//   Fact       copied from a registry record that cites evidence
//   Derived    calculated by scripts/release/engine.mjs from those records
//   Unverified builder-reported or not independently re-checked; never counted as verified

import { redactSensitive } from '../validate-registry.mjs'
import { STATE_TEXT, PROVENANCE_TEXT } from './engine.mjs'

export const ELIGIBILITY_TEXT = {
  released: 'Released and approved',
  'release-ready': 'Release-ready (all gates verified, approved)',
  'awaiting-owner-decision': 'Ready for the owner\'s release decision',
  'not-eligible': 'Not eligible for release',
  'not-scoped': 'Not scoped (no target version or scope document)'
}

const cell = s => String(s ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|')
const short = sha => (sha ? sha.slice(0, 7) : 'none')
const day = t => (t ? t.slice(0, 10) : 'never')
const pct = r => (r.percentage === null ? 'n/a' : `${r.percentage}%`)
const list = xs => (xs.length ? xs.join(', ') : 'none')

// Recursively redact every string in a JSON value.
export function redactJson(value) {
  if (typeof value === 'string') return redactSensitive(value)
  if (Array.isArray(value)) return value.map(redactJson)
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, redactJson(v)]))
  return value
}

export const toJson = value => JSON.stringify(redactJson(value), null, 2) + '\n'

function header(meta) {
  return [
    `Generated by \`${meta.command}\` from \`projects/registry.json\` (sha256 \`${meta.registryHash.slice(0, 12)}\`) as of ${meta.asOf}, staleness window ${meta.staleDays} days, engine v${meta.engineVersion}. Do not edit by hand; regenerate.`,
    '',
    '> A readiness percentage is progress, not release authorization. Only independently verified, current evidence counts, and only Joshua Small approves a release.',
    ''
  ]
}

export function renderDashboard(assessment, meta) {
  const L = ['# Project completion dashboard', '', ...header(meta)]
  L.push('| Project | Tier | Release target | Readiness (derived) | Verified / applicable gates | Blockers | Last evidence | Next recommended action |')
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const p of assessment.projects) {
    const r = p.derived.readiness
    const next = p.derived.nextActions[0]
    L.push(`| [${cell(p.name)}](projects/${p.id}.md) | ${p.tier} | ${cell(p.facts.targetVersion || 'Not scoped')} | ${pct(r)}, ${ELIGIBILITY_TEXT[r.eligibility].toLowerCase()} | ${r.verifiedGates} / ${r.applicableGates} | ${r.blockingFindings} (${r.registryBlockers} in registry) | ${day(p.facts.lastEvidenceAt)} | ${cell(next ? next.summary : 'None')} |`)
  }
  L.push('')
  L.push('## How to read this', '')
  L.push('- **Readiness** is verified gates divided by applicable gates, rounded down. Builder-reported results, CI runs and pass records made before an independent verifier was assigned count as zero.')
  L.push('- **Blockers** counts open blockers recorded in the registry (manual, governed records that automation never adds or removes) plus blockers the engine derived from the registry (proposals that are never written back). The registry-recorded count is in brackets.')
  L.push('- **Last evidence** is the newest evidence record in the registry for the project. Repository snapshots are refreshed by registry sync; see each project report for the snapshot date.')
  L.push('- **Next recommended action** is the highest-priority item derived from evidence: security, broken functionality, missing verification, CI, accessibility, release artifacts, then documentation.')
  L.push('')
  const deps = assessment.projects.flatMap(p => p.derived.dependencies.filter(d => d.kind !== 'cycle').map(d => ({ from: p.id, ...d })))
  L.push('## Declared dependencies', '')
  if (!deps.length && !assessment.dependencyCycles.length) L.push('None declared in the registry.', '')
  else {
    L.push('| Project | Depends on | Relationship | Required for release | Status (derived) |', '| --- | --- | --- | --- | --- |')
    for (const d of deps) L.push(`| ${d.from} | ${d.project} | ${d.relationship || 'unknown'} | ${d.requiredForRelease ? 'yes' : 'no'} | ${cell(d.message)} |`)
    for (const c of assessment.dependencyCycles) L.push(`| ${c[0]} | ${c[1]} | cycle | n/a | ${cell(`Circular dependency: ${c.join(' -> ')}`)} |`)
    L.push('')
  }
  return redactSensitive(L.join('\n'))
}

export function dashboardJson(assessment, meta) {
  return {
    kind: 'one-small-engineering/dashboard',
    ...metaJson(meta),
    projects: assessment.projects.map(p => {
      const r = p.derived.readiness
      return {
        id: p.id,
        name: p.name,
        tier: p.tier,
        facts: { targetVersion: p.facts.targetVersion, currentVersion: p.facts.currentVersion, releaseStatus: p.facts.releaseStatus, lastEvidenceAt: p.facts.lastEvidenceAt, snapshotObservedAt: p.facts.snapshotObservedAt },
        derived: {
          percentage: r.percentage,
          verifiedGates: r.verifiedGates,
          applicableGates: r.applicableGates,
          blockingFindings: r.blockingFindings,
          registryBlockers: r.registryBlockers,
          eligibility: r.eligibility,
          releaseReady: r.releaseReady,
          nextAction: p.derived.nextActions[0] ? p.derived.nextActions[0].text : null
        }
      }
    }),
    dependencyCycles: assessment.dependencyCycles
  }
}

function metaJson(meta) {
  return { generatedBy: meta.command, asOf: meta.asOf, staleDays: meta.staleDays, engineVersion: meta.engineVersion, registrySha256: meta.registryHash, notice: 'Readiness percentages are progress indicators, not release authorization. Only Joshua Small approves a release.' }
}

function blockerLines(blockers, empty) {
  if (!blockers.length) return [empty, '']
  const L = ['| Blocker | Source | Category | Gates | Description |', '| --- | --- | --- | --- | --- |']
  for (const b of blockers) L.push(`| ${b.id} | ${b.origin === 'registry' ? 'Fact: registry-recorded' : `Derived (proposed): ${cell(b.rule)}`} | ${b.category}${b.severity ? ` (${b.severity})` : ''} | ${list(b.gates)} | ${cell(b.description)} |`)
  return [...L, '']
}

export function renderProjectReport(p, meta, heading = '#') {
  const r = p.derived.readiness
  const f = p.facts
  const L = [`${heading} ${p.name} release readiness`, '', ...header(meta)]
  L.push(`${heading}# Summary (derived)`, '')
  L.push(`- Eligibility: **${ELIGIBILITY_TEXT[r.eligibility]}**.`)
  L.push(`- Readiness: ${pct(r)} (${r.verifiedGates} of ${r.applicableGates} applicable gates verified; ${r.remainingGates} remaining; ${r.totalGates - r.applicableGates} not applicable).`)
  L.push(`- Pre-publication gates verified: ${r.prePublication.verified} of ${r.prePublication.applicable}. Gates that can only be shown after publication or deployment are not needed for the owner's release decision.`)
  L.push(`- Gate states: ${Object.entries(r.byState).map(([k, v]) => `${STATE_TEXT[k].toLowerCase()} ${v}`).join(', ')}.`)
  L.push(`- Blocking findings: ${r.blockingFindings} (${r.registryBlockers} registry-recorded, ${r.blockingFindings - r.registryBlockers} derived).`)
  L.push(`- Missing independent verification (work exists, nobody independent has re-checked it): ${list(r.missingIndependentVerification)}.`)
  L.push(`- Release-ready: **${r.releaseReady ? 'yes' : 'no'}**. Ready means every applicable gate verified on current evidence, no open blocker, and Joshua Small's recorded approval.`)
  L.push('')
  L.push(`${heading}# Facts (registry)`, '')
  L.push(`- Tier: ${p.tier}. Current version: ${f.currentVersion || 'none'}. Target: ${f.targetVersion || 'none'}. Registry release status: ${f.releaseStatus}.`)
  L.push(`- Scope document: ${f.scopeDocument || 'none'}.`)
  L.push(`- Release candidate: ${f.candidate ? `${f.candidate.pullRequest ? `PR #${f.candidate.pullRequest}, ` : ''}${cell(f.candidate.ref)} at ${short(f.candidate.headSha)} (observed ${f.candidate.observedAt})${r.candidateMoved ? ' **moved since: evidence for it is stale**' : ''}` : 'not recorded'}.`)
  L.push(`- Open pull requests: ${f.openPullRequests.length ? f.openPullRequests.map(pr => `#${pr.number}${pr.draft ? ' (draft)' : ''} at ${short(pr.headSha)}`).join(', ') : 'none recorded'}.`)
  L.push(`- Repository snapshot: head ${short(f.head)} observed ${f.snapshotObservedAt}; last registry sync ${f.lastSyncedAt || 'never'}. Newest evidence: ${f.lastEvidenceAt || 'none'}.`)
  L.push(`- Builder: ${f.ownership.builder || 'not assigned'}. Verifier: ${f.ownership.verifier || 'not assigned'}. Approval: ${f.approval.status}${f.approval.approvedBy ? ` by ${f.approval.approvedBy}` : ''}.`)
  L.push(`- Registry next action (manual): ${f.registryNextAction}`)
  L.push('')
  L.push(`${heading}# Next actions (derived, in priority order)`, '')
  if (!p.derived.nextActions.length) L.push('None.')
  for (const a of p.derived.nextActions) L.push(`${a.rank}. ${a.text} _(priority ${a.priority}: ${a.bucket.toLowerCase()}; source ${a.source})_`)
  L.push('')
  L.push(`${heading}# Blockers`, '')
  L.push(`${heading}## Merge blockers`, '', ...blockerLines(p.derived.blockers.merge, 'None.'))
  L.push(`${heading}## Release blockers`, '', ...blockerLines(p.derived.blockers.release, 'None.'))
  L.push(`${heading}## Post-release enhancements (never block)`, '')
  if (!p.derived.blockers.postRelease.length) L.push('None recorded.')
  for (const e of p.derived.blockers.postRelease) L.push(`- ${e.text}`)
  L.push('')
  L.push(`${heading}# Gates`, '')
  L.push('| Gate | State (derived) | Registry status (fact) | Provenance | Last observed | Missing | Blockers | Next action |')
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const g of p.derived.gates) {
    L.push(`| ${g.id}${g.phase === 'post-publication' ? ' (post-publication)' : ''} | ${STATE_TEXT[g.state]} | ${g.registryStatus || 'missing'} | ${PROVENANCE_TEXT[g.provenance]} | ${day(g.lastObservedAt)} | ${cell(g.missing.join('; ') || 'nothing')} | ${list(g.blockers)} | ${cell(g.nextAction || 'none')} |`)
  }
  L.push('')
  L.push(`${heading}# Evidence by gate`, '')
  for (const g of p.derived.gates.filter(x => x.evidence.length)) {
    L.push(`- **${g.id}**: ${g.evidence.map(e => `[${e.id}](${e.url}) (${e.type}, ${e.result}, ${PROVENANCE_TEXT[e.provenance]}, ${short(e.commitSha)}, ${day(e.verifiedAt)}, recorded by ${cell(e.recordedBy)}${e.stale ? `; stale: ${cell(e.stale)}` : ''})`).join('; ')}`)
  }
  if (!p.derived.gates.some(x => x.evidence.length)) L.push('No gate cites evidence yet.')
  L.push('')
  L.push(`${heading}# Unverified (builder-reported or without an independent verifier)`, '')
  if (!p.unverified.length) L.push('None cited by a gate.')
  for (const u of p.unverified) L.push(`- ${u.gate}: ${u.evidence} (${PROVENANCE_TEXT[u.provenance]})`)
  L.push('')
  const deps = p.derived.dependencies
  if (deps.length) {
    L.push(`${heading}# Dependencies (derived from declarations)`, '')
    for (const d of deps) L.push(`- ${d.project} (${d.relationship || 'unknown'}, ${d.requiredForRelease ? 'required for release' : 'not required'}): ${d.kind}${d.blocking ? ', blocking' : ''}. ${d.message}`)
    L.push('')
  }
  if (p.derived.findings.length) {
    L.push(`${heading}# Registry findings`, '')
    for (const x of p.derived.findings) L.push(`- ${x.message}`)
    L.push('')
  }
  return redactSensitive(L.join('\n'))
}

export function projectJson(p, meta) {
  return { kind: 'one-small-engineering/project-readiness', ...metaJson(meta), project: p }
}
