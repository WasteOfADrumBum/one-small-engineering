// Verification dashboard renderers (Phase 4). Pure and deterministic. They extend the Phase 3
// dashboard (reports/dashboard.md), which stays the registry-only view; this one adds collector
// evidence, the six gate states and verification status. Every string is redacted on the way out.

import { redactJson } from '../release/render.mjs'
import { redactSensitive } from '../validate-registry.mjs'
import { GATE_STATES, GATE_STATE_TEXT, SEVERITIES } from './overlay.mjs'
import { issueReport } from './remediation.mjs'

const ELIGIBILITY = { released: 'released', 'release-ready': 'release-ready', 'awaiting-owner-decision': 'ready for owner decision', 'not-eligible': 'not eligible', 'not-scoped': 'not scoped' }
const cell = s => String(s ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|')
const short = sha => (sha ? sha.slice(0, 7) : 'none')
const day = t => (t ? t.slice(0, 10) : 'never')
const pct = v => (v === null || v === undefined ? 'n/a' : `${v}%`)
const STATE_SHORT = { independently_verified: 'verified', passed_by_builder: 'builder', failed: 'failed', inconclusive: 'inconclusive', not_tested: 'not tested', not_applicable: 'n/a' }

function header(meta) {
  return [
    `Generated by \`${meta.command}\` as of ${meta.asOf} from \`projects/registry.json\` (sha256 \`${meta.registryHash.slice(0, 12)}\`), \`verification/policy.json\` v${meta.policyVersion} (sha256 \`${meta.policyHash.slice(0, 12)}\`) and the evidence ledgers in \`verification/evidence/\`. Do not edit by hand; regenerate.`,
    '',
    '> Collector evidence is never verification. A gate counts only when a separate verifier named in the registry examined evidence for the exact commit and recorded it. Readiness is progress, not authorization; only Joshua Small approves a release.',
    ''
  ]
}

export function renderVerificationDashboard(a, meta) {
  const L = ['# Verification dashboard', '', ...header(meta)]
  L.push('| Project | Commit evaluated | Readiness | Verified / applicable | Gate states | Missing verification | Stale evidence | Blockers by severity | Merge / release | Last collection / verification | Next recommended action |')
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const p of a.projects) {
    const r = p.readiness
    const states = GATE_STATES.filter(s => p.gateStates[s]).map(s => `${p.gateStates[s]} ${STATE_SHORT[s]}`).join(', ')
    const sev = SEVERITIES.filter(s => p.blockersBySeverity[s]).map(s => `${p.blockersBySeverity[s]} ${s}`).join(', ') || 'none'
    L.push(`| [${cell(p.name)}](projects/${p.id}.md) | ${short(p.target.sha)} (${cell(p.target.source)}) | ${pct(r.percentage)}, ${ELIGIBILITY[r.eligibility]} | ${r.verifiedGates} / ${r.applicableGates} | ${states} | ${p.missingVerification.length} | ${p.staleEvidence.length} | ${sev} | ${p.mergeEligible ? 'merge eligible' : 'not merge eligible'} / ${p.releaseEligible ? 'release eligible' : 'not release eligible'} | ${day(p.lastCollection)} / ${day(p.lastVerification)} | ${cell(p.nextAction)} |`)
  }
  L.push('', '## Gate states', '')
  L.push('| State | Meaning |', '| --- | --- |')
  L.push('| Independently verified | A verifier named in the registry, who is not the builder or the builder\'s tool, examined current evidence for this commit and recorded a pass. The only state that counts toward readiness. |')
  L.push('| Passed by builder (not independent) | Builder-reported results or automated collector passes. Useful, but nobody independent has checked them. |')
  L.push('| Failed | A collector or a verifier recorded a failure on the evaluated commit. |')
  L.push('| Inconclusive | Evidence could not be collected, was not decisive, or is stale (wrong commit or expired). |')
  L.push('| Not tested | No evidence at all for the evaluated commit. |')
  L.push('| Not applicable | The registry marks the gate not applicable with a written rationale. |')
  L.push('', '## Collection runs', '')
  if (meta.runs && meta.runs.length) {
    L.push('| Project | Access | Collected | Reused | Executor |', '| --- | --- | --- | --- | --- |')
    for (const r of meta.runs) L.push(`| ${r.project} | ${cell(r.access === 'ok' ? 'readable' : `${r.access}: ${r.accessReason}`)} | ${r.collected} | ${r.reused} | ${cell(r.executor)} |`)
  } else L.push('No collection run recorded.')
  if (a.overlayErrors.length) L.push('', '## Verification records not applied', '', ...a.overlayErrors.map(e => `- ${cell(e)}`))
  L.push('')
  return redactSensitive(L.join('\n'))
}

export function renderVerificationProject(p, meta) {
  const r = p.readiness
  const L = [`# ${p.name}: verification`, '', ...header(meta)]
  L.push(`- Repository: ${p.repository}`)
  L.push(`- Commit evaluated: ${p.target.sha || 'unknown'} (${p.target.source})${p.target.drift ? `. Drift: ${p.target.drift}` : ''}`)
  L.push(`- Readiness: ${pct(r.percentage)} (${r.verifiedGates} of ${r.applicableGates} applicable gates independently verified; without applied verifications ${pct(r.previousPercentage)}). Eligibility: ${ELIGIBILITY[r.eligibility]}.`)
  L.push(`- Builder and verifier: ${r.ownershipValid ? 'assigned and distinct' : 'not both assigned, so no gate can be verified (an owner decision)'}`)
  L.push(`- Merge eligible: ${p.mergeEligible ? 'yes' : 'no'}. Release eligible: ${p.releaseEligible ? 'yes' : 'no'}.`)
  L.push(`- Last collection: ${p.lastCollection || 'never'}. Last valid verification: ${p.lastVerification || 'never'}.`)
  L.push(`- Next recommended action: ${p.nextAction}`)
  L.push('', '## Gates', '')
  L.push('| Gate | State | Automation | Collector evidence (current commit) | Stale evidence | Verification |', '| --- | --- | --- | --- | --- | --- |')
  for (const g of p.gates) {
    const ev = g.collectorEvidence.map(e => `${e.collector}: ${e.result}`).join('; ') || 'none'
    const ver = g.verifications.map(v => `${v.verifier}: ${v.result}${v.valid ? '' : ' (not counted)'}`).join('; ') || (g.humanOnly ? 'none (human-only gate)' : 'none')
    L.push(`| \`${g.id}\` | ${GATE_STATE_TEXT[g.state]} | ${g.automation}${g.manualReviewRequired ? ', manual review required' : ''} | ${cell(ev)} | ${g.staleEvidence.length} | ${cell(ver)} |`)
  }
  L.push('', '## Blockers', '')
  if (p.blockers.length) {
    L.push('| Blocker | Origin | Severity | Blocks | Description |', '| --- | --- | --- | --- | --- |')
    for (const b of p.blockers) L.push(`| ${b.id} | ${b.origin} | ${b.severity} | ${b.blocks} | ${cell(b.description)} |`)
  } else L.push('None.')
  L.push('', '## Findings from collectors', '')
  if (p.findings.length) {
    L.push('| Finding | Kind | Severity | Gates | Summary |', '| --- | --- | --- | --- | --- |')
    for (const f of p.findings) L.push(`| ${f.collector} | ${f.kind} | ${f.severity} | ${f.gates.join(', ') || 'none'} | ${cell(f.title)} |`)
    L.push('', 'Issue reports: [`remediation/' + p.id + '.md`](../remediation/' + p.id + '.md).')
  } else L.push('None at the evaluated commit.')
  L.push('', '## Verification requests', '')
  if (meta.requests && meta.requests[p.id]) {
    L.push('| Gate | Status | Method | Routed to | Evidence ready | Missing collectors |', '| --- | --- | --- | --- | --- | --- |')
    for (const q of meta.requests[p.id]) L.push(`| \`${q.gate}\` | ${cell(q.status)} | ${q.method}${q.humanOnly ? ' (human only)' : ''} | ${cell(q.routedTo || 'nobody')} | ${q.evidence.length} | ${q.missingCollectors.join(', ') || 'none'} |`)
  }
  if (p.verifications.length) {
    L.push('', '## Verification records', '')
    for (const v of p.verifications) L.push(`- ${v.id}: ${v.verifier} (${v.kind}, ${v.method}) ${v.result} on ${short(v.commitSha)}: ${v.valid ? 'counted' : `not counted: ${v.reasons.join('; ')}`}`)
  }
  L.push('', '## Related pull requests and remediation', '')
  const prs = p.relatedPullRequests.map(x => `- PR #${x.number}${x.draft ? ' (draft)' : ''}: ${x.url}`)
  const rem = p.remediation.map(x => `- Remediation: ${x.url || x.status}`)
  L.push(...(prs.length || rem.length ? [...prs, ...rem] : ['None recorded.']))
  L.push('')
  return redactSensitive(L.join('\n'))
}

export function renderIssueReports(p, meta) {
  const L = [`# ${p.name}: issue reports`, '', `As of ${meta.asOf}, commit ${p.target.sha || 'unknown'}. One section per collector result that is not a pass. Automation proposes no code fix unless a defect's fix is unambiguous; a person decides.`, '']
  for (const f of p.findings) L.push(issueReport(f), '')
  return redactSensitive(L.join('\n'))
}

export const toJson = v => JSON.stringify(redactJson(v), null, 2) + '\n'

export function dashboardJson(a, meta) {
  return {
    kind: 'one-small-engineering/verification-dashboard',
    command: meta.command,
    asOf: meta.asOf,
    registryHash: meta.registryHash,
    policyHash: meta.policyHash,
    policyVersion: meta.policyVersion,
    runs: meta.runs || [],
    overlayErrors: a.overlayErrors,
    projects: a.projects.map(p => ({
      id: p.id, name: p.name, tier: p.tier, repository: p.repository, target: p.target, readiness: p.readiness, gateStates: p.gateStates,
      gates: p.gates.map(g => ({ id: g.id, state: g.state, automation: g.automation, manualReviewRequired: g.manualReviewRequired, humanOnly: g.humanOnly, collectorEvidence: g.collectorEvidence.map(e => ({ id: e.id, collector: e.collector, result: e.result })), staleEvidence: g.staleEvidence.length, verifications: g.verifications })),
      missingVerification: p.missingVerification, staleEvidence: p.staleEvidence, blockersBySeverity: p.blockersBySeverity, blockers: p.blockers,
      mergeEligible: p.mergeEligible, releaseEligible: p.releaseEligible, lastCollection: p.lastCollection, lastVerification: p.lastVerification,
      nextAction: p.nextAction, findings: p.findings.map(({ reproduction, ...f }) => f), relatedPullRequests: p.relatedPullRequests, remediation: p.remediation,
      verificationRequests: (meta.requests || {})[p.id] || []
    }))
  }
}
